#!/usr/bin/env node
/**
 * Builds the APDS submission documents (docs/apds-submission/0[1-4]-*.md)
 * from spec/proposals/apds-additions/*.yaml and the prose fragments in
 * docs/apds-submission/src/. Mirrors the APDS 4.1 document set: Overview,
 * Information Model, Data Dictionary, Use Case Document.
 *
 *   node tools/build-apds-submission.mjs          validate and write
 *   node tools/build-apds-submission.mjs --check  validate; fail if stale
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ADDITIONS = join(ROOT, 'spec', 'proposals', 'apds-additions');
const VOCAB = join(ROOT, 'spec', 'proposals', 'apds-4.1-vocabulary.json');
const APDS_API = join(ROOT, 'spec', 'vendor', 'apds', '4.1', 'apds-api-4.1.yaml');
const OUT = join(ROOT, 'docs', 'apds-submission');
const SRC = join(OUT, 'src');
const CHECK = process.argv.includes('--check');

const SECTIONS = ['Overview', 'Information model', 'Use cases'];
const STEREOTYPES = new Set(['D2Class', 'D2Identifiable', 'D2VersionedIdentifiable']);
const MULTIPLICITY = /^(\d+)\.\.(\d+|\*)$/;
const UPPER = /^[A-Z][A-Za-z0-9]*$/;
const LOWER = /^[a-z][A-Za-z0-9]*$/;
const APDS_DOMAINS = ['Place', 'Occupancy', 'Rates', 'Right', 'Session', 'Observation', 'Quote', 'EnergyInfrastructure', 'PkCommon'];
const TIER_NAMES = { 1: 'propose now', 2: 'proven in APX, propose next', 3: 'for discussion' };
const GENERATED = '<!-- Generated by tools/build-apds-submission.mjs from spec/proposals/. Do not edit by hand. -->';

const errors = [];
const fail = (where, msg) => errors.push(`${where}: ${msg}`);
const lf = (text) => text.replace(/\r\n/g, '\n');
const read = (path) => lf(readFileSync(path, 'utf8'));
const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

// ---------- load ----------

function loadDomains() {
  return readdirSync(ADDITIONS)
    .filter((f) => f.endsWith('.yaml'))
    .map((f) => ({ file: f, slug: basename(f, '.yaml'), ...yaml.load(read(join(ADDITIONS, f))) }))
    .sort((a, b) => a.order - b.order || (a.slug < b.slug ? -1 : 1));
}

function loadFragment(slug) {
  const path = join(SRC, `${slug}.md`);
  if (!existsSync(path)) { fail(`src/${slug}.md`, 'missing prose fragment'); return {}; }
  const text = read(path);
  const parts = {};
  const marks = [...text.matchAll(/^## (Overview|Information model|Use cases)\s*$/gm)];
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : text.length;
    parts[m[1]] = text.slice(m.index + m[0].length, end).trim();
  });
  for (const s of SECTIONS) if (!parts[s]) fail(`src/${slug}.md`, `missing "## ${s}" section`);
  return parts;
}

function readText(name) {
  const path = join(SRC, name);
  if (!existsSync(path)) { fail(`src/${name}`, 'missing'); return ''; }
  return read(path).trim();
}

// ---------- vocabulary ----------

// APDS names come from two places: the Data Dictionary (names only, in the
// vocabulary file) and the vendored API document. Either is enough for a
// name to count as existing in APDS 4.1.
function buildVocabulary(domains) {
  const v = JSON.parse(readFileSync(VOCAB, 'utf8'));
  const api = yaml.load(read(APDS_API)).components.schemas;
  const apds = new Set([...v.datatypes, ...Object.keys(v.enumerations), ...Object.keys(api)]);
  for (const names of Object.values(v.classesByPackage)) names.forEach((n) => apds.add(n));
  const enumValues = {};
  for (const [name, values] of Object.entries(v.enumerations)) enumValues[name] = new Set(values);
  for (const [name, s] of Object.entries(api)) {
    if (Array.isArray(s.enum)) s.enum.forEach((x) => (enumValues[name] ??= new Set()).add(x));
  }
  const proposed = new Map();
  for (const d of domains) for (const p of d.packages ?? []) {
    for (const c of p.classes ?? []) if (c.change === 'new') proposed.set(c.name, d.file);
    for (const e of p.enumerations ?? []) if (e.change === 'new') proposed.set(e.name, d.file);
  }
  // Properties APDS already declares on each class (own and allOf parts),
  // so an extension cannot re-propose one.
  const apiProps = {};
  for (const [name, s] of Object.entries(api)) {
    const parts = [s, ...(s.allOf ?? [])];
    apiProps[name] = new Set(parts.flatMap((p) => Object.keys(p.properties ?? {})));
  }
  // Type prefixes name the domain, as in the APDS Data Dictionary.
  const domainNames = new Set([...APDS_DOMAINS, ...domains.map((d) => d.domain)]);
  return { apds, proposed, enumValues, apiProps, domains: domainNames };
}

// ---------- validate ----------

function checkType(where, type, vocab) {
  if (typeof type !== 'string') return fail(where, 'type/target missing');
  const m = type.match(/^([A-Z][A-Za-z0-9]*)\.([A-Z][A-Za-z0-9]*)(?: \(([A-Z][A-Za-z0-9]*)\.([A-Z][A-Za-z0-9]*)\))?$/);
  if (!m) return fail(where, `"${type}" is not Package.Name or Package.Name (Package.Target)`);
  for (const prefix of [m[1], m[3]].filter(Boolean)) {
    if (!vocab.domains.has(prefix)) fail(where, `prefix "${prefix}" is not an APDS or proposed domain`);
  }
  for (const name of [m[2], m[4]].filter(Boolean)) {
    if (!vocab.apds.has(name) && !vocab.proposed.has(name)) fail(where, `unknown type "${name}"`);
  }
}

function checkMember(where, member, kind, vocab) {
  const name = kind === 'association' ? member.end : member.name;
  if (!LOWER.test(name ?? '')) fail(where, `${kind} name "${name}" is not lowerCamelCase`);
  if (!MULTIPLICITY.test(member.multiplicity ?? '')) fail(`${where}.${name}`, `bad multiplicity "${member.multiplicity}"`);
  if (!member.designation || !member.definition) fail(`${where}.${name}`, 'designation and definition required');
  checkType(`${where}.${name}`, kind === 'association' ? member.target : member.type, vocab);
}

function checkCommon(where, item, vocab, seen) {
  if (!UPPER.test(item.name ?? '')) fail(where, `name "${item.name}" is not UpperCamelCase`);
  if (!['new', 'extend'].includes(item.change)) fail(where, 'change must be new or extend');
  if (![1, 2, 3].includes(item.tier)) fail(where, 'tier must be 1, 2 or 3');
  if (!item.definition || !item.rationale || !item.apx) fail(where, 'definition, rationale and apx required');
  if (item.change === 'new' && vocab.apds.has(item.name)) fail(where, 'already exists in APDS 4.1; use change: extend');
  if (item.change === 'extend' && !vocab.apds.has(item.name)) fail(where, 'not in APDS 4.1; use change: new');
  const key = `${item.change} ${item.name}`;
  if (seen.has(key)) fail(where, `also proposed in ${seen.get(key)}`);
  seen.set(key, where);
}

function checkClass(where, c, vocab, seen) {
  checkCommon(where, c, vocab, seen);
  if (c.change === 'new' && !STEREOTYPES.has(c.stereotype)) fail(where, `stereotype "${c.stereotype}" not allowed`);
  if (!['B', 'C'].includes(c.level)) fail(where, 'level must be B or C');
  if (c.parent) checkType(`${where}.parent`, c.parent, vocab);
  (c.attributes ?? []).forEach((a) => checkMember(where, a, 'attribute', vocab));
  (c.associations ?? []).forEach((a) => checkMember(where, a, 'association', vocab));
  const members = [...(c.attributes ?? []).map((a) => a.name), ...(c.associations ?? []).map((a) => a.end)];
  members.filter((m, i) => members.indexOf(m) !== i).forEach((m) => fail(`${where}.${m}`, 'member named twice'));
  if (c.change !== 'extend') return;
  if (!members.length) fail(where, 'extend adds nothing');
  const existing = vocab.apiProps[c.name] ?? new Set();
  members.filter((m) => existing.has(m)).forEach((m) => fail(`${where}.${m}`, 'already a member of the APDS class'));
}

function checkEnumeration(where, e, vocab, seen) {
  checkCommon(where, e, vocab, seen);
  const existing = vocab.enumValues[e.name];
  if (e.change === 'extend' && !existing) fail(where, 'not an APDS 4.1 enumeration');
  if (!e.values?.length) fail(where, 'no values');
  const names = (e.values ?? []).map((v) => v.name);
  names.filter((n, i) => names.indexOf(n) !== i).forEach((n) => fail(`${where}.${n}`, 'value named twice'));
  for (const v of e.values ?? []) {
    if (!LOWER.test(v.name ?? '')) fail(where, `value "${v.name}" is not lowerCamelCase`);
    if (!v.designation || !v.definition) fail(`${where}.${v.name}`, 'designation and definition required');
    if (e.change === 'extend' && existing?.has(v.name)) fail(`${where}.${v.name}`, 'value already in APDS 4.1');
  }
}

function validate(domains, vocab) {
  const seen = new Map();
  const packages = new Map();
  for (const d of domains) {
    if (!d.domain || typeof d.order !== 'number' || !d.summary) fail(d.file, 'domain, order and summary required');
    for (const p of d.packages ?? []) {
      const at = `${d.file} ${p.name}`;
      if (!p.location?.startsWith('D2Payload/')) fail(at, 'location must start with D2Payload/');
      const prior = packages.get(p.name);
      if (prior && (prior.location !== p.location || prior.status !== p.status)) fail(at, `location or status differs from ${prior.file}`);
      packages.set(p.name, { location: p.location, status: p.status, file: d.file });
      (p.classes ?? []).forEach((c) => checkClass(`${at}.${c.name}`, c, vocab, seen));
      (p.enumerations ?? []).forEach((e) => checkEnumeration(`${at}.${e.name}`, e, vocab, seen));
    }
  }
}

// ---------- render helpers ----------

const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').trim();
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
const demote = (md) => md.replace(/^(#{3,5}) /gm, '#$1 ');

function changeLabel(item, kind) {
  if (kind === 'enum') return item.change === 'new' ? 'New enumeration' : 'New values for an APDS enumeration';
  return item.change === 'new' ? 'New class' : 'Additions to an APDS class';
}

function allItems(domains) {
  return domains.flatMap((d) => (d.packages ?? []).flatMap((p) => [
    ...(p.classes ?? []).map((c) => ({ d, p, item: c, kind: 'class' })),
    ...(p.enumerations ?? []).map((e) => ({ d, p, item: e, kind: 'enum' })),
  ]));
}

function header(title, edition) {
  return [GENERATED, '', `# ${title}`, '', `*Proposed additions to the APDS data model · ${edition}*`, ''].join('\n');
}

function countLine(items) {
  const n = (f) => items.filter(f).length;
  return `${items.length} proposals: ${n((i) => i.kind === 'class' && i.item.change === 'new')} new classes, `
    + `${n((i) => i.kind === 'class' && i.item.change === 'extend')} additions to existing APDS classes, `
    + `${n((i) => i.kind === 'enum' && i.item.change === 'new')} new enumerations and `
    + `${n((i) => i.kind === 'enum' && i.item.change === 'extend')} sets of new values for existing APDS enumerations. `
    + `Tier 1: ${n((i) => i.item.tier === 1)}, Tier 2: ${n((i) => i.item.tier === 2)}, Tier 3: ${n((i) => i.item.tier === 3)}.`;
}

function summaryTable(items) {
  return table(['Element', 'Change', 'Package', 'Tier', 'Level'], items.map(({ p, item, kind }) => [
    `\`${item.name}\``, changeLabel(item, kind), p.name, item.tier, kind === 'class' ? item.level : '—',
  ]));
}

// Where each proposal comes from in APX, kept out of the committee tables.
function traceabilityAnnex(items) {
  return ['## Annex A (informative) Traceability to APX', '',
    'Each proposal comes from a data element already used in APX. This annex lists where, for reviewers who want to see it in use.', '',
    table(['Element', 'Domain', 'APX source'], items.map(({ d, item }) => [`\`${item.name}\``, d.domain, item.apx])), ''].join('\n');
}

// ---------- 01 overview ----------

function renderOverview(domains, frags, edition) {
  const out = [header('APX Data Specification: Overview', edition), readText('_overview-intro.md'), ''];
  out.push('## Overview of the proposed data specification', '');
  for (const d of domains) {
    out.push(`### ${d.domain} Data Specification`, '', d.summary.trim(), '', demote(frags[d.slug].Overview ?? ''), '');
  }
  out.push(readText('_overview-outro.md'), '');
  return out.join('\n');
}

// ---------- 02 information model ----------

function renderInformationModel(domains, frags, edition) {
  const items = allItems(domains);
  const out = [header('APX Data Specification: Information Model', edition), readText('_im-intro.md'), ''];
  out.push('## Proposed changes at a glance', '', countLine(items), '');
  for (const tier of [1, 2, 3]) {
    const t = items.filter((i) => i.item.tier === tier);
    out.push(`### Tier ${tier}: ${TIER_NAMES[tier]}`, '', t.length ? summaryTable(t) : 'None.', '');
  }
  out.push('## Data model', '');
  for (const d of domains) {
    out.push(`### ${d.domain}`, '', d.summary.trim(), '', demote(frags[d.slug]['Information model'] ?? ''), '');
    out.push(`#### Elements proposed for ${d.domain}`, '', summaryTable(items.filter((i) => i.d === d)), '');
  }
  out.push(readText('_im-outro.md'), '', traceabilityAnnex(items));
  return out.join('\n');
}

// ---------- 03 data dictionary ----------

function packageTables(p, num, next) {
  const classes = p.classes ?? [];
  const specs = classes.filter((c) => c.parent);
  const assoc = classes.flatMap((c) => (c.associations ?? []).map((a) => [c.name, a.end, a.designation, a.definition, a.multiplicity, a.target]));
  const attrs = classes.flatMap((c) => (c.attributes ?? []).map((a) => [c.name, a.name, a.designation, a.definition, a.multiplicity, a.type]));
  const block = (n, title, rows, head) => [
    `**A.1.${num}.${n} ${title} of the "${p.name}" package**`, '',
    rows.length ? `*Table A.${next()} -- ${title} of the "${p.name}" package*\n\n${table(head, rows)}`
      : `There are no proposed ${title.toLowerCase()} in the "${p.name}" package.`, '',
  ];
  return [
    ...block(2, 'Classes', classes.map((c) => [c.name, c.change === 'new' ? 'new' : 'extends APDS', c.designation,
      c.definition, c.stereotype ?? '(existing)', c.abstract ? 'yes' : 'no']),
    ['Class name', 'Change', 'Designation', 'Definition', 'Stereotype', 'Abstract']),
    ...block(3, 'Specializations', specs.map((c) => [c.name, c.parent]), ['Class name', 'Parent class name']),
    ...block(4, 'Associations', assoc, ['Class name', 'Association end', 'Designation', 'Definition', 'Multiplicity', 'Target']),
    ...block(5, 'Attributes', attrs, ['Class name', 'Attribute name', 'Designation', 'Definition', 'Multiplicity', 'Type']),
  ];
}

function renderPackage(p, num, next) {
  return [
    `### A.1.${num} "${p.name}" package${p.status === 'new' ? ' (new)' : ''}`, '',
    `**A.1.${num}.1 Location of "${p.name}" package.** The location of the "${p.name}" package is:`, '',
    `\`-- ${p.location}\``, '',
    ...packageTables(p, num, next),
  ].join('\n');
}

function renderEnumeration(e, num, next) {
  const extend = e.change === 'extend';
  return [
    `### A.3.${num} The <<D2Enumeration>> "${e.name}"${extend ? ' (values proposed for addition)' : ''}`, '',
    e.definition.trim(), '',
    `*Table A.${next()} -- Values ${extend ? 'proposed for' : 'contained in'} the enumeration "${e.name}"*`, '',
    table(['Enumerated value name', 'Designation', 'Definition'], e.values.map((v) => [v.name, v.designation, v.definition])), '',
  ].join('\n');
}

function mergePackages(domains) {
  const merged = new Map();
  for (const d of domains) for (const p of d.packages ?? []) {
    const cur = merged.get(p.name) ?? { ...p, classes: [], enumerations: [] };
    cur.classes.push(...(p.classes ?? []));
    cur.enumerations.push(...(p.enumerations ?? []));
    merged.set(p.name, cur);
  }
  const list = [...merged.values()];
  list.forEach((p) => p.classes.sort(byName));
  return list.sort(byName);
}

function renderDataDictionary(domains, edition) {
  const out = [header('APX Data Specification: Data Dictionary', edition), readText('_dd-intro.md'), ''];
  let n = 0;
  const next = () => ++n;
  const packages = mergePackages(domains);
  out.push('## A.1 Data dictionary of proposed packages for "Parking"', '');
  packages.forEach((p, i) => out.push(renderPackage(p, i + 1, next), ''));
  out.push('## A.2 Data dictionary of <<D2Datatype>> for "Parking"', '',
    'No new datatypes are proposed. Every attribute uses an existing APDS 4.1 datatype, class or enumeration, or one proposed in this document.', '');
  out.push('## A.3 Data dictionary of <<D2Enumeration>> for "Parking"', '');
  const enums = packages.flatMap((p) => p.enumerations).sort(byName);
  enums.forEach((e, i) => out.push(renderEnumeration(e, i + 1, next)));
  return out.join('\n');
}

// ---------- 04 use cases ----------

function renderUseCases(domains, frags, edition) {
  const out = [header('APX Data Specification: Use Case Document', edition), readText('_uc-intro.md'), ''];
  out.push('## C.3 APX use cases', '');
  let n = 0;
  for (const d of domains) {
    out.push((frags[d.slug]['Use cases'] ?? '').replace(/^### (.+)$/gm, (_, t) => `### C.3.${++n} ${t}`), '');
  }
  out.push(readText('_uc-outro.md'), '');
  return out.join('\n');
}

// ---------- main ----------

function editionLine() {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  return `Draft for the APDS committee · based on APDS 4.1 (2026-01-14) · APX ${pkg.version}`;
}

function writeOrCheck(docs) {
  let stale = 0;
  for (const [name, text] of Object.entries(docs)) {
    const path = join(OUT, name);
    const body = text.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
    const current = existsSync(path) ? read(path) : '';
    if (current === body) continue;
    if (CHECK) { console.error(`[apds-submission] ${name} is stale; run node tools/build-apds-submission.mjs`); stale++; }
    else writeFileSync(path, body);
  }
  return stale;
}

function main() {
  const domains = loadDomains();
  validate(domains, buildVocabulary(domains));
  const frags = Object.fromEntries(domains.map((d) => [d.slug, loadFragment(d.slug)]));
  const slugs = new Set(domains.map((d) => d.slug));
  readdirSync(SRC).filter((f) => f.endsWith('.md') && !f.startsWith('_') && !slugs.has(basename(f, '.md')))
    .forEach((f) => fail(`src/${f}`, 'no matching spec/proposals/apds-additions YAML'));
  const edition = editionLine();
  const docs = {
    '01-overview.md': renderOverview(domains, frags, edition),
    '02-information-model.md': renderInformationModel(domains, frags, edition),
    '03-data-dictionary.md': renderDataDictionary(domains, edition),
    '04-use-cases.md': renderUseCases(domains, frags, edition),
  };
  if (errors.length) {
    console.error(`[apds-submission] ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  if (writeOrCheck(docs)) process.exit(1);
  console.log(`[apds-submission] ${domains.length} domains, ${countLine(allItems(domains))}`);
}

main();
