#!/usr/bin/env node
/**
 * Concatenates docs/standard/*.md into ONE document: site/apx-standard.md.
 *
 * Why: the written standard is twenty-odd files, which is right for editing
 * and wrong for review. A working group reads, annotates, and circulates a
 * single artifact. This produces that artifact from the same sources CI
 * validates, so the combined document can never say something the parts do
 * not.
 *
 * Each part keeps its own `#` title, with an anchor emitted before it so the
 * table of contents works in GitHub, in a browser, and after a pandoc
 * conversion to PDF.
 *
 * Runs as part of `npm run docs:build`. Output lands in the gitignored site/
 * directory and is published with the rest of the documentation site.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STANDARD = join(ROOT, 'docs', 'standard');
const SITE = join(ROOT, 'site');
const OUT = join(SITE, 'apx-standard.md');

mkdirSync(SITE, { recursive: true });

const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

const files = readdirSync(STANDARD).filter((f) => f.endsWith('.md')).sort();
if (files.length === 0) {
  console.error('[docs:standard] FAIL no parts found in docs/standard/');
  process.exit(1);
}

const slug = (file) => file.replace(/\.md$/, '');

const parts = files.map((file) => {
  const body = readFileSync(join(STANDARD, file), 'utf8').trimEnd();
  const heading = body.split('\n').find((line) => line.startsWith('# '));
  return { file, body, title: heading ? heading.replace(/^#\s*/, '') : slug(file) };
});

const today = new Date().toISOString().slice(0, 10);

const front = [
  '# APX — APDS Parking eXtensions',
  '',
  '**The written standard, complete, in one document.**',
  '',
  `Edition ${version} · draft · compiled ${today}`,
  '',
  'This document is generated by concatenating the parts in `docs/standard/`',
  'of the APX repository. It is a convenience for review: those parts remain',
  'the editable source, and the bundled OpenAPI document is normative over',
  'prose for APX-defined paths (Part 0 §0.5).',
  '',
  'Repository: <https://github.com/rneubauer/apx>  ',
  'API reference: <https://rneubauer.github.io/apx/reference.html>  ',
  'Registries: <https://rneubauer.github.io/apx/registries/>  ',
  'Edition manifest: `spec/edition.json`, the exact artifacts this edition pins',
  '',
  '---',
  '',
  '## Contents',
  '',
  ...parts.map((p, i) => `${i + 1}. [${p.title}](#${slug(p.file)})`),
  '',
  '---',
  '',
].join('\n');

const body = parts.map((p) => `<a id="${slug(p.file)}"></a>\n\n${p.body}\n`).join('\n---\n\n');

writeFileSync(OUT, `${front}${body}\n`);

const lineCount = (front + body).split('\n').length;
console.log(`[docs:standard] site/apx-standard.md — ${parts.length} parts, ${lineCount} lines`);
