/** Markdown helpers shared by the APX Specification renderers. */

// Escape pipes everywhere, and backslashes and < > outside code spans so
// that placeholders such as <domain> are not swallowed as HTML.
export const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').trim()
  .split(/(`[^`]*`)/)
  .map((part, i) => (i % 2 ? part : part.replace(/\\/g, '\\\\').replace(/</g, '&lt;').replace(/>/g, '&gt;')))
  .join('')
  .replace(/\|/g, '\\|');
/** One Markdown table row. Each cell is cleaned with cell(). */
export const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
/** A Markdown table from a header row and an array of data rows (each an array of cells). */
export const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
/** Sort comparison for objects with a `name`, in plain code-unit order. */
export const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
/** Wraps text in backticks, for inline code. */
export const code = (s) => `\`${s}\``;

/**
 * The top of a generated document: an optional "Generated by" banner, the title and the edition line.
 *
 * @param {string} title The document title.
 * @param {string} edition The edition line, printed in italics.
 * @param {string} [generatedBy] The generator name. When given, the banner says the file is generated and not to edit it by hand.
 * @returns {string} The Markdown text.
 */
export function header(title, edition, generatedBy) {
  const banner = generatedBy ? [`<!-- Generated by ${generatedBy}. Do not edit by hand. -->`, ''] : [];
  return [...banner, `# ${title}`, '', `*${edition}*`, ''].join('\n');
}

// How APX relates each element to APDS, for the "APDS status" column.
export function apdsStatus(cls) {
  if (!cls.proposedAs.length) return 'APX only';
  return cls.proposedAs.map((p) => `Proposed: ${p.name} (Tier ${p.tier})`).join('; ');
}

// Pull per-value definitions out of prose such as "`detected` — the
// finding was recorded" or "`full` (default — the ordinary list)".
export function valueDefinitions(description, values) {
  const out = {};
  const text = String(description ?? '');
  for (const v of values) {
    const esc = v.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const m = text.match(new RegExp('`' + esc + '`\\s*(?:—|–|:|-|=|\\()\\s*([^`\\n]+?)(?=\\s*(?:[;,]\\s*`|\\)\\s*[,;.]?\\s*`|\\.\\s|\\n|$))'));
    if (m) out[v] = m[1].replace(/\)$/, '').trim();
  }
  return out;
}
